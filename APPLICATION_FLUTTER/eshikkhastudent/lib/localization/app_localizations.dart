class AppLanguage {
  static final ValueNotifier<String> current = ValueNotifier<String>('en');

  static bool get isEnglish => current.value == 'en';
  static bool get isBangla => current.value == 'bn';

  static void changeLanguage(String langCode) {
    if (current.value != langCode) {
      current.value = langCode;
    }
  }

  static void toggleLanguage() {
    current.value = current.value == 'en' ? 'bn' : 'en';
  }
}

